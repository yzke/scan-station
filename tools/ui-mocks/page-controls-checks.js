async (page) => {
  if (page.url() !== 'http://127.0.0.1:18761/') throw new Error('Refusing non-mock origin');
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const read = () => page.evaluate(async () => (await fetch('/__mock__')).json());
  const mock = change => page.evaluate(async value => (await fetch('/__mock__', {method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(value)})).json(), change);
  const order = () => page.locator('#grid .pg').evaluateAll(nodes => nodes.map(node => Number(node.dataset.page)));
  const waitOrder = values => page.waitForFunction(values => JSON.stringify([...document.querySelectorAll('#grid .pg')].map(node => Number(node.dataset.page))) === JSON.stringify(values), values);
  const online = {state:'online',message:'扫描仪已连接',supported_dpi:[150,200,300],duplex_supported:true,supports_page_rescan:true};
  const refresh = async () => { await page.locator('#btnHistoryRefresh').click(); };
  const finish = async doc => {
    await mock({document:doc,active_id:null,scanner:online});
    await page.locator('#btnDeviceRefresh').click();
    await refresh();
    await page.waitForFunction(() => !document.getElementById('btnScan').disabled);
  };
  const results = [];
  await waitOrder([1,2,3,4]);
  await page.evaluate(() => {window.__pageNodes = Object.fromEntries([...document.querySelectorAll('#grid .pg')].map(node => [node.dataset.page,node.querySelector('img')]));});
  const source = await page.locator('.pg[data-page="1"] .drag-handle').boundingBox();
  const target = await page.locator('.pg[data-page="4"]').boundingBox();
  await page.mouse.move(source.x + source.width/2, source.y + source.height/2);
  await page.mouse.down();
  await page.mouse.move(source.x + source.width/2 + 20, source.y + source.height/2 + 15, {steps:5});
  await page.mouse.move(target.x + 7, target.y + 80, {steps:10});
  await page.mouse.move(target.x + 8, target.y + 82);
  assert(await page.locator('.pg.drop-before').count() === 1, 'Drag did not show a clear insertion indicator');
  await page.screenshot({path:'output/playwright/scanner-page-drag-indicator.png',fullPage:true});
  await page.mouse.up();
  await waitOrder([2,3,1,4]);
  await page.waitForFunction(() => !document.getElementById('btnReverse').disabled);
  let data = await read();
  let reorder = data.logs.findLast(item => item.path.endsWith('/reorder'));
  assert(JSON.stringify(reorder.body.pages) === '[2,3,1,4]' && reorder.body.order_revision === 0, 'Drag did not persist the complete permutation and revision');
  assert(await page.evaluate(() => [...document.querySelectorAll('#grid .pg')].every(node => window.__pageNodes[node.dataset.page] === node.querySelector('img'))), 'Reorder recreated image nodes');
  results.push('Real desktop drag shows insertion marker and persists full stable-ID permutation with revision; image nodes retained');

  await page.locator('.pg[data-page="1"] .move-up').focus();
  await page.keyboard.press('Enter');
  await waitOrder([2,1,3,4]);
  await page.waitForFunction(() => !document.getElementById('btnReverse').disabled);
  assert(await page.evaluate(() => document.activeElement.closest('.pg')?.dataset.page === '1'), 'Keyboard move lost focus');
  await page.reload();
  await waitOrder([2,1,3,4]);
  const downloading = page.waitForEvent('download');
  await page.locator('#btnPdf').click();
  await downloading;
  data = await read();
  assert(JSON.stringify(data.logs.findLast(item => item.path.endsWith('/pdf')).pdf_order) === '[2,1,3,4]', 'PDF did not use saved preview order');
  results.push('Keyboard controls retain focus; reload and PDF use the persisted preview order');

  await page.locator('#btnReverse').click();
  await waitOrder([4,3,1,2]);
  await page.waitForFunction(() => !document.getElementById('btnReverse').disabled);
  await mock({failNext:{path:'/scan/order-doc/reorder',status:409,body:{error:'页序已变化，请刷新后重试'}}});
  await page.locator('.pg[data-page="4"] .move-down').click();
  await page.waitForFunction(() => document.getElementById('notice').textContent.includes('页序已变化'));
  await waitOrder([4,3,1,2]);
  results.push('Explicit reverse only; rejected version-conflict reorder restores server order');

  await page.getByRole('button',{name:'重扫第 2 页',exact:true}).click();
  assert((await page.locator('.rescan-instruction').innerText()).includes('只将需要替换的这一页'), 'Single-sheet instruction missing');
  assert((await page.locator('#rescanOptions').innerText()).includes('300 DPI') && (await page.locator('#rescanOptions').innerText()).includes('单面'), 'Original per-page settings missing');
  const postsBeforeCancel = (await read()).logs.filter(item=>item.path.includes('/rescan/')).length;
  await page.locator('#btnRescanCancel').click();
  assert((await read()).logs.filter(item=>item.path.includes('/rescan/')).length === postsBeforeCancel, 'Cancel started a scan');
  results.push('Rescan asks for exactly one correctly oriented sheet; cancel sends no request');

  await page.getByRole('button',{name:'重扫第 2 页',exact:true}).click();
  const oldSrc = await page.locator('.pg[data-page="3"] img').getAttribute('src');
  await page.evaluate(() => { window.__replacementImage = document.querySelector('.pg[data-page="3"] img'); });
  await page.locator('#btnRescanConfirm').click();
  await page.waitForFunction(() => document.querySelector('.pg[data-page="3"]').classList.contains('replacing'));
  data = await read();
  const replacement = data.logs.findLast(item=>item.path.includes('/rescan/'));
  assert(replacement.path === '/scan/order-doc/rescan/3' && JSON.stringify(replacement.body) === '{}', 'Rescan sent unstable position or changed name/options');
  assert(JSON.stringify(data.documents[0].last_rescan_settings) === '{"dpi":300,"duplex":false,"max_pages":1}', 'Original page settings not retained in mock contract');
  assert(await page.locator('.pg[data-page="3"] img').getAttribute('src') === oldSrc, 'Old page changed before replacement succeeded');
  assert(await page.locator('#btnReverse').isDisabled() && await page.locator('.rescan-button').first().isDisabled() && await page.locator('.delete-button').first().isDisabled(), 'Page edits not locked during replacement');
  await page.screenshot({path:'output/playwright/scanner-page-rescan-pending.png',fullPage:true});
  const nextDetails = JSON.parse(JSON.stringify(data.documents[0].page_details));
  nextDetails[3].revision = 2;
  await finish({id:'order-doc',state:'done',rescan_page:null,page_details:nextDetails});
  await page.waitForFunction(() => document.querySelector('.pg[data-page="3"] img').getAttribute('src').endsWith('?v=2'));
  assert(JSON.stringify(await order()) === '[4,3,1,2]', 'Replacement changed page order or count');
  assert(await page.evaluate(() => window.__replacementImage === document.querySelector('.pg[data-page="3"] img')), 'Replacement removed the stable image node');
  assert(await page.locator('.pg[data-page="2"] img').getAttribute('src') === '/scan/order-doc/page/2?v=1', 'Replacement refreshed another page');
  assert(await page.locator('#fileName').inputValue() === '手动归档文件', 'Replacement changed the manual file name');
  results.push('Confirmed rescan targets stable page ID, retains old image while busy, then cache-busts only that slot without name/order changes');

  await page.getByRole('button',{name:'重扫第 3 页',exact:true}).click();
  const failureSrc = await page.locator('.pg[data-page="1"] img').getAttribute('src');
  await page.locator('#btnRescanConfirm').click();
  await page.waitForFunction(() => document.querySelector('.pg[data-page="1"]').classList.contains('replacing'));
  await finish({id:'order-doc',state:'error',rescan_page:null,msg:'重扫失败，原页已保留'});
  assert(await page.locator('.pg[data-page="1"] img').getAttribute('src') === failureSrc, 'Failed replacement lost original page');
  assert((await page.locator('#status').innerText()).includes('原页已保留'), 'Replacement error is not visible');
  results.push('Failed replacement retains original image and displays its failure');

  await mock({scanner:{...online,supports_page_rescan:false}});
  await page.locator('#btnDeviceRefresh').click();
  await page.waitForFunction(() => document.querySelector('.rescan-button').disabled);
  assert((await page.locator('#rescanHelp').innerText()).includes('更新扫描仪程序'), 'Unsupported gateway lacks a short update explanation');
  await page.setViewportSize({width:390,height:844});
  await page.locator('.pg[data-page="2"] .move-up').click();
  await waitOrder([4,3,2,1]);
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile layout has horizontal overflow');
  await page.screenshot({path:'output/playwright/scanner-page-controls-mobile.png',fullPage:true});
  results.push('Unsupported rescan stays disabled with update note; mobile move controls work without overflow');
  const result = {passed:true,checks:results,mockOrigin:page.url()};
  await page.evaluate(value=>{window.__scanUiPageResult=value;},result);
  console.log(JSON.stringify(result,null,2));
}
